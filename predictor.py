"""Inference service that loads the saved Random Forest pipeline and predicts demand."""

from __future__ import annotations

import math
from typing import Any

import joblib
import pandas as pd

from app.config import MIN_TRAINING_RECORDS, MODEL_ARTIFACT_PATH
from app.database.base import DatabaseRepository
from app.ml.train_model import CATEGORICAL_FEATURES, NUMERIC_FEATURES, get_model_status


class ModelNotReadyError(RuntimeError):
    """Raised when the demand prediction model cannot run due to insufficient data or missing artifact."""


def predict_food_demand(
    db: DatabaseRepository,
    food_item: str,
    expected_attendance: int,
    day_of_week: str,
    special_event: bool,
    holiday: bool,
    previous_sales: float,
    safety_buffer_pct: float = 10.0,
) -> dict[str, Any]:
    """Load saved Random Forest model and return predicted demand + recommended prep."""
    status = get_model_status(db)
    if status["status"] != "ready" or not MODEL_ARTIFACT_PATH.exists():
        raise ModelNotReadyError(
            f"Prediction unavailable: {status.get('message', 'Insufficient training data.')} "
            f"(Current records: {status['current_total_records']}, required: {MIN_TRAINING_RECORDS})."
        )

    pipeline = joblib.load(MODEL_ARTIFACT_PATH)
    is_weekend = 1 if day_of_week in ("Saturday", "Sunday") else 0

    input_df = pd.DataFrame(
        [
            {
                "food_item": food_item,
                "day_of_week": day_of_week,
                "expected_attendance": int(expected_attendance),
                "special_event": 1 if special_event else 0,
                "holiday": 1 if holiday else 0,
                "previous_sales": float(previous_sales),
                "is_weekend": is_weekend,
            }
        ],
        columns=CATEGORICAL_FEATURES + NUMERIC_FEATURES,
    )

    raw_pred = float(pipeline.predict(input_df)[0])
    predicted_demand = max(1, int(round(raw_pred)))
    buffer_multiplier = 1.0 + (float(safety_buffer_pct) / 100.0)
    recommended_preparation = max(predicted_demand, int(math.ceil(predicted_demand * buffer_multiplier)))

    factors: list[str] = [
        f"Expected campus attendance of {expected_attendance:,} students",
        f"Historical demand pattern for {food_item} on {day_of_week}",
        f"Recent baseline sales of {round(previous_sales)} portions",
    ]
    if special_event:
        factors.append("Special campus event uplift applied (+event footfall)")
    if holiday:
        factors.append("Campus holiday reduction factored into demand")
    factors.append(f"Configurable {safety_buffer_pct:.1f}% safety buffer added for preparation target")

    explanation = (
        f"Estimate generated by {status['algorithm']} (test MAE: {status['mae']} portions, "
        f"RMSE: {status['rmse']} portions, R²: {status.get('r2_score')}). Key context considered: "
        + "; ".join(factors)
        + "."
    )

    return {
        "food_item": food_item,
        "expected_attendance": int(expected_attendance),
        "day_of_week": day_of_week,
        "special_event": bool(special_event),
        "holiday": bool(holiday),
        "previous_sales": float(previous_sales),
        "safety_buffer_pct": float(safety_buffer_pct),
        "predicted_demand": predicted_demand,
        "recommended_preparation": recommended_preparation,
        "model_version": status["model_version"],
        "mae": status["mae"],
        "rmse": status["rmse"],
        "r2_score": status.get("r2_score"),
        "factors_considered": factors,
        "explanation": explanation,
        "advisory_note": (
            "Predictions are data-driven estimates based on historical patterns and context—not "
            "guaranteed outcomes. Please review alongside live kitchen judgment before cooking."
        ),
    }
